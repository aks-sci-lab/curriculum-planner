function curriculumOfficialSubjectKey(name) {
  return String(name ?? "").normalize("NFKC")
    .replace(/[*＊★☆■↔]/g, "")
    .replace(/[⋅·•ㆍ∙]/g, "")
    .replace(/\s+/g, "")
    .toLowerCase();
}

var curriculumOfficialSubjectIndex = null;
function curriculumOfficialSubjects() {
  if (!curriculumOfficialSubjectIndex) {
    curriculumOfficialSubjectIndex = new Map();
    for (const [name, category, area, type] of CURRICULUM_OFFICIAL_SUBJECT_ROWS) {
      curriculumOfficialSubjectIndex.set(curriculumOfficialSubjectKey(name), {
        name,
        category: CURRICULUM_OFFICIAL_CATEGORIES[category],
        area: CURRICULUM_OFFICIAL_AREAS[area],
        type: CURRICULUM_OFFICIAL_TYPES[type]
      });
    }
  }
  return curriculumOfficialSubjectIndex;
}

function findCurriculumOfficialSubject(name) {
  return curriculumOfficialSubjects().get(curriculumOfficialSubjectKey(name)) || null;
}

// 편제표 과목 종류(공통/일반선택/진로선택/융합선택)로 편성 가능한지 검사한다.
// '*'(특목고 과목)·'★'(전문교과) 표시 과목은 진로선택으로, 전문교과는 진로선택으로 편성할 수 있다.
function curriculumOfficialTypeCheck(name, detail) {
  const official = findCurriculumOfficialSubject(name);
  const raw = String(name ?? "");
  if (/☆|■/.test(raw)) return { ok: true, official, reason: "고시 외·교과특성화 표시 과목" };
  if (!official) return { ok: false, official: null, reason: "2022 개정 교육과정 과목 목록에 없는 과목명입니다." };
  if (!detail || official.type === detail) return { ok: true, official, reason: "" };
  if (detail === "진로선택" && (/[*＊★]/.test(raw) || official.category === "전문교과")) {
    return { ok: true, official, reason: "표시 과목의 진로선택 편성" };
  }
  return { ok: false, official, reason: `목록상 '${official.type}' 과목이므로 '${detail}'(으)로 편성할 수 없습니다.` };
}
